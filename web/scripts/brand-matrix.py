#!/usr/bin/env python3
"""Regenerate the CUA brand contrast matrix.

The project instructions reference a full WCAG table at
/home/ubuntu/cua-brand-contrast-matrix.md. That file did not exist in this
sandbox, so this script builds it from the brand palette instead of trusting a
hand-typed table. Ratios are computed in sRGB with the WCAG relative-luminance
formula, so the numbers match what a browser reports.

Run:
    python3 scripts/brand-matrix.py > /home/ubuntu/cua-brand-contrast-matrix.md

Pass thresholds follow WCAG 2.2 AA: 4.5:1 for body text, 3:1 for large text
(24px regular, or 18.66px bold).
"""

TEXT = {
    "Black": (0, 0, 0),
    "Catholic Blue": (10, 50, 85),
    "Catholic Red": (178, 31, 44),
    "Bright Blue": (36, 89, 169),
    "Bright Red": (232, 47, 53),
    "Light Red": (233, 105, 85),
    "Light Blue": (109, 172, 222),
    "Lux": (177, 143, 80),
    "Yellow": (255, 214, 92),
    "Light Blue-Green": (181, 225, 225),
    "Grey": (167, 169, 172),
    "White": (255, 255, 255),
}

BACKGROUNDS = {
    "White": (255, 255, 255),
    "Sandstone": (247, 243, 237),
    "Limestone": (239, 235, 233),
    "Grey": (167, 169, 172),
    "Catholic Blue": (10, 50, 85),
    "Catholic Red": (178, 31, 44),
    "Bright Blue": (36, 89, 169),
    "Black": (0, 0, 0),
}

# brand.catholic.edu names these three as the light neutrals text sits on.
LIGHT_NEUTRALS = ["White", "Sandstone", "Limestone"]


def lum(rgb):
    def chan(v):
        v /= 255
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (chan(v) for v in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(a, b):
    x, y = lum(a), lum(b)
    hi, lo = max(x, y), min(x, y)
    return (hi + 0.05) / (lo + 0.05)


def mark(r):
    if r >= 4.5:
        return "AA body + large"
    if r >= 3.0:
        return "large only"
    return "fail"


print("# CUA brand contrast matrix (WCAG 2.2 AA, computed sRGB)")
print()
print("Generated by `web/scripts/brand-matrix.py`. Text colours down, "
      "background colours across. Each cell is the ratio, then the verdict.")
print()
for bg_name, bg in BACKGROUNDS.items():
    print(f"## Text on {bg_name}")
    print()
    print("| Text colour | Ratio | Body text | Large text | Notes |")
    print("| --- | --- | --- | --- | --- |")
    for t_name, t in TEXT.items():
        if t_name == bg_name:
            continue
        r = ratio(t, bg)
        body = "pass" if r >= 4.5 else "fail"
        large = "pass" if r >= 3.0 else "fail"
        note = ""
        if bg_name in LIGHT_NEUTRALS and body == "fail":
            note = "no text on this neutral"
        if r < 3.0:
            note = "decorative only"
        print(f"| {t_name} | {r:.2f}:1 | {body} | {large} | {note} |")
    print()

print("## Rules this table supports")
print()
print("- Body text on any light neutral: Black, Catholic Blue, Catholic Red, "
      "Bright Blue.")
print("- Large text on White also tolerates Bright Red, Light Red and Lux; "
      "Light Red and Lux fail on Sandstone and Limestone, so treat them as "
      "White-only.")
print("- Never text on a light neutral: Yellow, Light Blue-Green, Light Blue, "
      "Grey.")
print("- Reversed fills for panels and buttons: White on Catholic Blue, White "
      "on Catholic Red.")
print("- Focus indicator: Bright Blue clears 3:1 non-text contrast (SC 1.4.11) "
      "on White (6.83:1), Sandstone (6.17:1) and Limestone (5.76:1), and the "
      "SC 2.4.13 minimum area. On Grey it is only 2.90:1, so do not place a "
      "Bright Blue ring on a Grey fill; use Catholic Blue there instead.")
print("- WCAG 2.2 SC 2.4.11: focus must not be hidden. The sticky header "
      "reserves `--header-height` and every focus ring sits inside the layer.")
